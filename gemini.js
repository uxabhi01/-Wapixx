import { GoogleGenerativeAI } from '@google/generative-ai';
import { config } from './config.js';

let genAI = null;

// Limit maximum characters per message to prevent denial of service and API quota exhaustion
const MAX_INPUT_CHARS = 4000;

// Maximum number of message exchanges to keep in memory (to manage token count and costs)
const MAX_HISTORY_TURNS = 10;

/**
 * Initializes the Gemini API client.
 */
export function initGemini() {
  if (!config.hasValidApiKey) {
    console.warn('⚠️  WARNING: GEMINI_API_KEY is not configured in .env! AI automated replies will be disabled.');
    return false;
  }

  try {
    genAI = new GoogleGenerativeAI(config.geminiApiKey);
    return true;
  } catch (error) {
    console.error('Failed to initialize Google Generative AI client:', error?.message || error);
    return false;
  }
}

// In-memory store for active chat histories
// Keys: chatId, Values: Array of message history objects
const chatHistories = new Map();

/**
 * Generates an automated reply using Google Gemini.
 * @param {string} chatId - The standard WhatsApp chat ID
 * @param {string} incomingMessageText - The text message received
 * @returns {Promise<string>} The reply text generated by Gemini
 */
export async function generateAIReply(chatId, incomingMessageText) {
  // Input validation: ensure incoming message is valid text
  if (typeof incomingMessageText !== 'string' || !incomingMessageText.trim()) {
    return '';
  }

  // Sanitize and limit input length to protect API quota
  const sanitizedInput = incomingMessageText.trim().slice(0, MAX_INPUT_CHARS);

  // Initialize Gemini if not already initialized
  if (!genAI) {
    if (!initGemini()) {
      return 'Hello! (Note: Auto-reply is active, but AI responses are disabled because GEMINI_API_KEY is not set in .env).';
    }
  }

  try {
    const model = genAI.getGenerativeModel({
      model: config.geminiModel,
      systemInstruction: config.botPersona,
    });

    // Retrieve or initialize history for this contact
    if (!chatHistories.has(chatId)) {
      chatHistories.set(chatId, []);
    }
    const history = chatHistories.get(chatId);

    // Create a chat session with the existing history
    const chat = model.startChat({
      history: history,
      generationConfig: {
        maxOutputTokens: 600,
        temperature: 0.7,
      }
    });

    // Send the incoming message to Gemini
    const result = await chat.sendMessage(sanitizedInput);
    const response = await result.response;
    const replyText = response.text()?.trim() || 'Hello! Thank you for reaching out. How can we assist you today?';

    // Get the updated history (includes the new message and reply)
    const updatedHistory = await chat.getHistory();
    
    // Keep history trimmed to the last MAX_HISTORY_TURNS turns (1 turn = user msg + model reply = 2 entries)
    const maxEntries = MAX_HISTORY_TURNS * 2;
    if (updatedHistory.length > maxEntries) {
      chatHistories.set(chatId, updatedHistory.slice(-maxEntries));
    } else {
      chatHistories.set(chatId, updatedHistory);
    }

    return replyText;
  } catch (error) {
    // Log error internally without exposing sensitive details or stack traces to the user
    console.error(`Error generating Gemini reply for chat ${chatId}:`, error?.message || error);
    
    // Clear corrupted history so subsequent messages are not blocked
    chatHistories.delete(chatId);
    
    // Friendly, secure fallback response for users in case of API errors
    return 'Thank you for reaching out! We received your message and will assist you shortly.';
  }
}

/**
 * Clears the chat history for a specific contact.
 * Useful if the conversation context needs to be reset.
 * @param {string} chatId 
 */
export function clearChatHistory(chatId) {
  if (chatHistories.has(chatId)) {
    chatHistories.delete(chatId);
    return true;
  }
  return false;
}
